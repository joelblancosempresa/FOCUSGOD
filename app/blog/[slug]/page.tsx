export async function generateStaticParams() {
  return Object.keys(posts).map((slug) => ({ slug }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const post = posts[slug];
  if (!post) return {};
  return {
    title: `${post.title} — FocusGod Blog`,
    description: post.content.slice(0, 160).replace(/[*#\n]/g, " ").trim(),
  };
}

export default async function BlogPost({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const post = posts[slug];
  if (!post) notFound();

  const paragraphs = post.content
    .trim()
    .split("\n\n")
    .filter(Boolean);

  return (
    <>
      <Navbar />
      <main className="pt-14">
        <article className="max-w-2xl mx-auto px-6 py-16">
          <div className="mb-8">
            <div className="flex items-center gap-3 mb-4">
              <span className="bg-blue text-white text-xs font-bold px-3 py-1 rounded-full">
                {post.category}
              </span>
              <span className="text-ink3 text-sm">{post.date}</span>
            </div>
            <h1 className="text-3xl sm:text-4xl font-semibold text-ink leading-snug mb-6">
              {post.title}
            </h1>
            <div className="h-px bg-black/10" />
          </div>

          <div className="prose-custom">
            {paragraphs.map((p, i) => {
              if (p.startsWith("**") && p.endsWith("**")) {
                return (
                  <h2 key={i} className="text-xl font-semibold text-ink mt-8 mb-3">
                    {p.replace(/\*\*/g, "")}
                  </h2>
                );
              }
              if (p.startsWith("- ")) {
                return (
                  <ul key={i} className="list-disc pl-5 mb-4 space-y-1">
                    {p.split("\n").map((item, j) => (
                      <li key={j} className="text-ink2 leading-relaxed">
                        {item.replace(/^- /, "")}
                      </li>
                    ))}
                  </ul>
                );
              }
              if (p.startsWith('"') || p.includes("— ")) {
                return (
                  <blockquote key={i} className="border-l-4 border-blue pl-5 my-6 italic text-ink2 text-lg leading-relaxed">
                    {p}
                  </blockquote>
                );
              }
              const parts = p.split(/(\*\*[^*]+\*\*)/g);
              return (
                <p key={i} className="text-ink2 leading-relaxed mb-4 text-[1.05rem]">
                  {parts.map((part, j) =>
                    part.startsWith("**") ? (
                      <strong key={j} className="font-bold text-ink">
                        {part.replace(/\*\*/g, "")}
                      </strong>
                    ) : (
                      part
                    )
                  )}
                </p>
              );
            })}
          </div>

          <div className="mt-12 pt-8 border-t border-black/10">
            <div
              className="rounded-3xl px-8 py-10 text-center text-white"
              style={{ background: "linear-gradient(135deg, #1CB0F6 0%, #0EA5E9 100%)" }}
            >
              <h3 className="text-2xl font-semibold mb-3">¿Listo para poner a Dios primero?</h3>
              <p className="text-white/80 mb-6">Descarga FocusGod y empieza mañana por la mañana.</p>
              <a
                href="/download"
                className="inline-block bg-white text-blue font-semibold px-8 py-4 rounded-2xl hover:opacity-90 transition-opacity"
              >
                Descargar gratis →
              </a>
            </div>
          </div>

          <div className="mt-8">
            <Link href="/blog" className="text-blue font-semibold text-sm hover:underline">
              ← Volver al blog
            </Link>
          </div>
        </article>
      </main>
      <Footer />
    </>
  );
}
